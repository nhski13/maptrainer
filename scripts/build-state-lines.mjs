/**
 * Regenerates src/data/state-lines.ts — the US state boundaries the globe draws.
 *
 *   npm i --no-save us-atlas
 *   node scripts/build-state-lines.mjs
 *
 * Source is the Census Bureau's 1:10,000,000 state cartographic boundaries, as
 * packaged by us-atlas (ISC). Three things happen to it on the way in, and all
 * three are about weight: the globe already draws every coastline in the world
 * from world-atlas, and shipping a second, better copy of the American one to
 * light up forty-nine internal lines is not a trade worth making.
 *
 *   • Only the interior mesh survives. An arc that isn't shared by two states
 *     is coastline or an international frontier — the country layer's job —
 *     and that is three quarters of the source by point count.
 *   • Coordinates are quantised to GRID degrees and delta-encoded along each
 *     arc, which is what topojson does and for the same reason: neighbouring
 *     points on a boundary differ in the last couple of digits, so the deltas
 *     are small integers where the absolute values are long decimals.
 *   • Alaska and Hawaii contribute nothing — neither borders another state —
 *     so what comes out is the lower 48, and the cap below says where it is.
 *     A frame pointed at Eurasia can then skip the path in one comparison.
 *
 * Net: ~38 kB gzipped of topology becomes ~11 kB of arcs.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { mesh } from 'topojson-client';
import { geoCentroid, geoDistance } from 'd3-geo';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Coordinate grid, in degrees. 1e-4° is about 11 m — an order of magnitude
 * finer than anything a 1:10m boundary claims to know, and small enough that
 * the quantisation is invisible at the deepest zoom the globe reaches.
 */
const GRID = 1e-4;

const us = require('us-atlas/states-10m.json');
const lines = mesh(us, us.objects.states, (a, b) => a !== b).coordinates;

// ── delta encoding ────────────────────────────────────────────────────
const q = (v) => Math.round(v / GRID);
const arcs = [];
for (const line of lines) {
  const out = [];
  let px = 0;
  let py = 0;
  for (const [lon, lat] of line) {
    const x = q(lon);
    const y = q(lat);
    if (out.length > 0 && x === px && y === py) continue; // quantised onto its neighbour
    out.push(x - px, y - py);
    px = x;
    py = y;
  }
  if (out.length >= 4) arcs.push(out); // a one-point arc draws nothing
}

// ── the cap, computed on the decoded (i.e. shipped) coordinates ───────
const decoded = arcs.map((a) => {
  const pts = [];
  let x = 0;
  let y = 0;
  for (let i = 0; i < a.length; i += 2) {
    x += a[i];
    y += a[i + 1];
    pts.push([x * GRID, y * GRID]);
  }
  return pts;
});
const centre = geoCentroid({ type: 'MultiLineString', coordinates: decoded });
let radius = 0;
for (const line of decoded) {
  for (const p of line) radius = Math.max(radius, geoDistance(centre, p));
}

const round = (v) => Number(v.toFixed(6));
/** Rounded outward: a cap that has shrunk by a rounding step is not a bound. */
const roundUp = (v) => Math.ceil(v * 1e6) / 1e6;
const points = decoded.reduce((n, l) => n + l.length, 0);

const body = `/**
 * US state lines — interior boundaries only, at 1:10,000,000.
 *
 * Generated by scripts/build-state-lines.mjs from us-atlas (ISC), which
 * packages the US Census Bureau's cartographic boundary files. Do not edit by
 * hand. ${arcs.length} arcs, ${points} points.
 *
 * Coastlines and the Canadian and Mexican frontiers are deliberately absent:
 * the globe draws those from world-atlas along with every other country's, and
 * a second copy at a second resolution would only be two lines where there is
 * one border. Alaska and Hawaii border no other state, so nothing of them
 * survives the mesh — what is here is the lower 48.
 */

/** Coordinates are integer multiples of this, delta-encoded along each arc. */
const GRID = ${GRID};

/** Per arc: [lon, lat, dLon, dLat, …] in GRID units, from an implicit origin. */
const ARCS: number[][] = ${JSON.stringify(arcs)};

function decode(): [number, number][][] {
  return ARCS.map((arc) => {
    const line: [number, number][] = [];
    let x = 0;
    let y = 0;
    for (let i = 0; i < arc.length; i += 2) {
      x += arc[i];
      y += arc[i + 1];
      line.push([x * GRID, y * GRID]);
    }
    return line;
  });
}

/** The mesh as GeoJSON, ready for d3-geo's path. */
export const stateLines = {
  type: 'MultiLineString' as const,
  coordinates: decode(),
};

/**
 * Smallest cap containing the mesh — centre in degrees, radius in radians.
 * Lets a frame decide in one comparison whether the lower 48 can be on the
 * near hemisphere at all, rather than clipping every segment away one by one.
 */
export const stateLinesCap: { center: [number, number]; radius: number } = {
  center: [${round(centre[0])}, ${round(centre[1])}],
  radius: ${roundUp(radius)},
};
`;

writeFileSync(join(root, 'src/data/state-lines.ts'), body);
console.log(`state-lines.ts: ${arcs.length} arcs, ${points} points, ${body.length} bytes`);
